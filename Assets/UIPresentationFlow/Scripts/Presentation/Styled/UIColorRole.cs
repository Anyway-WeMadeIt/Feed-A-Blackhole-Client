// A palette color by what it is for. The theme palette (UIPalette.ThemeColors) has one color per role.
public enum UIColorRole
{
    TextMain,   // Title, Body
    TextWeak,   // Caption
    Accent,     // progress fills, selected states
    Surface,    // chips/panels drawn by code
    Line,       // outlines, tracks, dividers
    Backdrop,   // screen background behind the background image
}
